    fun t(key: String, params: Map<String, Any?> = emptyMap(), lang: String = "en"): String {
        val dict = if (lang.equals("id", ignoreCase = true)) ID else EN
        val raw = dict[key] ?: EN[key] ?: return key
        if (raw !is String) return raw.toString()
        if (params.isEmpty()) return raw
        return Regex("""\{(\w+)\}""").replace(raw) { mr ->
            val p = mr.groupValues[1]
            params[p]?.toString() ?: ""
        }
    }

    @Suppress("UNCHECKED_CAST")
    fun list(key: String, lang: String = "en"): List<String> {
        val dict = if (lang.equals("id", ignoreCase = true)) ID else EN
        val raw = dict[key] ?: EN[key]
        return (raw as? List<String>) ?: emptyList()
    }
